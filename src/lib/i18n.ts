const DICTS: Record<Locale, Dict> = { en, fr };

function makeT(locale: Locale) {
  const tag = locale === "fr" ? "fr-FR" : "en-US";
  const nf = new Intl.NumberFormat(tag);
  const d = DICTS[locale];
  const num = (n: number) => nf.format(n);
  const money = (n: number) => (locale === "fr" ? `${num(Math.round(n))} $` : `$${num(Math.round(n))}`);
  const date = (ms: number) =>
    new Date(ms).toLocaleDateString(tag, { year: "numeric", month: "long", day: "numeric", timeZone: "UTC" });

  /** e.g. { value: "6", unit: "days to go", kind: "live" } */
  const timeLeft = (deadline: number | null, now = Date.now()) => {
    if (!deadline) return { value: "—", unit: d.time.notLaunched, kind: "draft" as const, short: d.time.shortDraft };
    const ms = deadline - now;
    if (ms <= 0) return { value: "0", unit: d.time.ended, kind: "ended" as const, short: d.time.shortEnded };
    const hours = ms / 3_600_000;
    if (hours < 1) {
      const n = Math.max(1, Math.ceil(ms / 60_000));
      return { value: String(n), unit: d.time.minutes(n), kind: "live" as const, short: d.time.shortMinutes(n) };
    }
    if (hours < 48) {
      const n = Math.floor(hours);
      return { value: String(n), unit: d.time.hours(n), kind: "live" as const, short: d.time.shortHours(n) };
    }
    const n = Math.floor(hours / 24);
    return { value: String(n), unit: d.time.days(n), kind: "live" as const, short: d.time.shortDays(n) };
  };

  return {
    ...d,
    locale,
    num,
    money,
    date,
    timeLeft,
    shortTimeLeft: (deadline: number | null) => timeLeft(deadline).short,
    category: (slug: string) => d.categories[slug] ?? slug,
  };
}

export type T = ReturnType<typeof makeT>;

/** Saved choice first, then the browser's preferred language, then English. */
export async function getLocale(): Promise<Locale> {
  const saved = (await cookies()).get(LANG_COOKIE)?.value;
  if (isLocale(saved)) return saved;
  const accept = (await headers()).get("accept-language") ?? "";
  const first = accept.split(",")[0]?.split(";")[0]?.trim().toLowerCase() ?? "";
  return first === "fr" || first.startsWith("fr-") ? "fr" : "en";
}

export const getT = cache(async (): Promise<T> => makeT(await getLocale()));
